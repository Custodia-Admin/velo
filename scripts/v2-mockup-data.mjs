#!/usr/bin/env node
// Generates docs/design/mockups/v2-data.js for the Velo v2 identity mockups:
//   * lucide icon nodes (same icon set the app uses, lucide-react in node_modules)
//   * real route geometry: elevation profiles + plan-view paths for the routes
//     the mockups show (Perugia world bundle for the two baked routes, the
//     generated scenic route table for the rest).
// Usage: node scripts/v2-mockup-data.mjs   (from the repo root; deterministic)
import { readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ICON_DIR = resolve(REPO, 'node_modules/lucide-react/dist/esm/icons');
const ICONS = [
  'play', 'pause', 'flag', 'bluetooth', 'settings', 'tv', 'clapperboard', 'arrow-left',
  'chevron-right', 'battery-medium', 'heart', 'camera', 'video', 'download', 'upload', 'map',
  'mountain', 'x', 'check', 'refresh-cw', 'users', 'cloud-sun', 'wind', 'circle-help',
  'loader-circle', 'cloud-fog', 'sun', 'moon', 'gauge', 'picture-in-picture-2', 'maximize-2',
  'volume-2', 'skip-forward', 'trophy', 'mail', 'image', 'circle-alert',
];

function icon(name) {
  const src = readFileSync(resolve(ICON_DIR, `${name}.js`), 'utf8');
  const m = src.match(/createLucideIcon\("[^"]+", (\[[\s\S]*?\])\);/);
  if (!m) throw new Error(`icon ${name}: no node list`);
  // node list is a JS literal of [tag, {attrs}] pairs; drop React keys
  const nodes = Function(`return ${m[1]}`)();
  return nodes.map(([tag, attrs]) => {
    const { key: _k, ...rest } = attrs;
    return [tag, rest];
  });
}

const gz = (p) => JSON.parse(gunzipSync(readFileSync(resolve(REPO, p))).toString('utf8'));

function simplify(pts, n) {
  if (pts.length <= n) return pts;
  const out = [];
  for (let i = 0; i < n; i++) out.push(pts[Math.round((i * (pts.length - 1)) / (n - 1))]);
  return out;
}

function pack({ id, xs, ys, hs, ds, distanceM, ascentM }) {
  // plan view: normalise into a 1000-unit box keeping aspect (y up -> svg y down)
  const minX = Math.min(...xs), maxX = Math.max(...xs), minY = Math.min(...ys), maxY = Math.max(...ys);
  const span = Math.max(maxX - minX, maxY - minY) || 1;
  const path = simplify(xs.map((x, i) => [x, ys[i]]), 220).map(([x, y]) => [
    Math.round(((x - minX) / span) * 1000),
    Math.round(((maxY - y) / span) * 1000),
  ]);
  const prof = simplify(ds.map((d, i) => [d, hs[i]]), 160).map(([d, h]) => [Math.round(d), Math.round(h * 10) / 10]);
  return {
    id,
    distanceM: Math.round(distanceM),
    ascentM: Math.round(ascentM),
    box: [Math.round(((maxX - minX) / span) * 1000), Math.round(((maxY - minY) / span) * 1000)],
    spanM: Math.round(span),
    path,
    profile: prof,
  };
}

const routes = {};

// baked world routes (local metres, 10 m steps)
const world = gz('public/worlds/perugia/routes.json.gz');
for (const r of world.routes ?? world) {
  let asc = 0;
  for (let i = 1; i < r.h.length; i++) asc += Math.max(0, r.h[i] - r.h[i - 1]);
  routes[r.id] = pack({ id: r.id, xs: r.x, ys: r.y, hs: r.h, ds: r.s, distanceM: r.lengthM, ascentM: asc });
}

// generated scenic table ([lat, lon, ele]); parse the literal out of the TS file
const ts = readFileSync(resolve(REPO, 'src/lib/scenicRouteData.ts'), 'utf8');
const WANT = ['scenic-trasimeno-shore', 'scenic-lugano-melide', 'scenic-locarno-brissago', 'scenic-valle-maggia'];
for (const id of WANT) {
  const re = new RegExp(`'${id}': \\{\\s*distanceM: (\\d+),\\s*ascentM: (\\d+),[\\s\\S]*?points: (\\[\\[[\\s\\S]*?\\]\\]),`);
  const m = ts.match(re);
  if (!m) throw new Error(`route ${id} not found in scenicRouteData.ts`);
  const pts = JSON.parse(m[3]);
  const lat0 = pts[0][0], lon0 = pts[0][1];
  const kx = 111320 * Math.cos((lat0 * Math.PI) / 180), ky = 110540;
  const xs = pts.map((p) => (p[1] - lon0) * kx), ys = pts.map((p) => (p[0] - lat0) * ky), hs = pts.map((p) => p[2]);
  const ds = [0];
  for (let i = 1; i < pts.length; i++) ds.push(ds[i - 1] + Math.hypot(xs[i] - xs[i - 1], ys[i] - ys[i - 1]));
  routes[id] = pack({ id, xs, ys, hs, ds, distanceM: Number(m[1]), ascentM: Number(m[2]) });
}

const icons = Object.fromEntries(ICONS.map((n) => [n, icon(n)]));
const out = `// GENERATED by scripts/v2-mockup-data.mjs — do not edit by hand.
// Icons: lucide (ISC). Route geometry: © OpenStreetMap contributors (ODbL),
// elevation Copernicus GLO-90 / Perugia world bake (see docs/worlds/CREDITS.md).
window.V2_DATA = ${JSON.stringify({ icons, routes })};
`;
writeFileSync(resolve(REPO, 'docs/design/mockups/v2-data.js'), out);
console.log('wrote docs/design/mockups/v2-data.js', Object.keys(icons).length, 'icons', Object.keys(routes).length, 'routes', out.length, 'bytes');
for (const r of Object.values(routes)) console.log(r.id, r.distanceM, 'm', r.ascentM, 'm up', 'box', r.box.join('x'), 'span', r.spanM);
